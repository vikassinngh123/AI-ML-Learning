import os
from fastapi import FastAPI , Response, HTTPException
from pydantic import BaseModel, Field
from transformers import pipeline
from supabase import create_client, Client

#SUPABASE Setup
SUPABASE_URL = os.environ.get("SUPABASE_URL", "supabase_url")
SUPABASE_KEY = os.environ.get("SUPABASE_KEY", "supabase_key")
supabase: Client = create_client(SUPABASE_URL, SUPABASE_KEY)

#ML Model Setup
try:
    print("Loading sentiment model...")
    sentiment_classifier = pipeline(
        "sentiment-analysis",
        model="./sentiment_model",
        tokenizer="./sentiment_model"
    )
except Exception as e:
    sentiment_classifier = None

#Schema
class Review(BaseModel):
  review: str |None= Field(..., min_length=3, description="Review Text")
  stars: int  |None = Field(default=3, ge=1, le=5, description="Stars 1-5")

class ReviewResponse(BaseModel):
  message: str


app=FastAPI(title="Review Sentiment API")

#ENDPOINT
@app.post("/submit_review", response_model= ReviewResponse)
def customer_review(payload : Review):
  if sentiment_classifier is None:
    try:
      supabase.table("not_analysied_customer_reviews").insert({
              "review_text": payload.review,
              "stars": payload.stars
          }).execute()
    except Exception as e:
          raise HTTPException(status_code=500, detail="Failed to save to database")

    return {"message": "Review submitted successfully!"}

  model_output = sentiment_classifier(payload.review)[0]
  predicted_sentiment = model_output["label"]

  try:
        supabase.table("customer_reviews").insert({
            "review_text": payload.review,
            "sentiment": predicted_sentiment,
            "stars": payload.stars
        }).execute()
  except Exception as e:
        raise HTTPException(status_code=500, detail="Failed to save to database")

  return{"message": "Review submitted successfully!"}